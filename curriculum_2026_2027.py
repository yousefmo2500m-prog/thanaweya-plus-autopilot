def get_academic_calendar_state(now: datetime.datetime | None = None) -> Dict[str, Any]:
    """
    حساب السنة الدراسية والأسبوع الفعلي ونوع اليوم تلقائياً لأي سنة (2026/2027، 2027/2028، ... للأبد).
    - السبت إلى الأربعاء: مذاكرة وتقدم فعلي في الدروس (regular_study)
    - الخميس والجمعة: معسكر التقييم الأسبوعي الرسمي لوزارة التربية والتعليم ولمّ المتراكم (weekly_assessment)
    - فترة الامتحانات الشهرية الرسمية (18–22 أكتوبر، 22–26 نوفمبر، 21–25 مارس، 25–29 أبريل): (monthly_exam)
    """
    if now is None:
        cairo_tz = datetime.timezone(datetime.timedelta(hours=2))
        now = datetime.datetime.now(cairo_tz)

    today = now.date()
    start_year = today.year if today.month >= 9 else today.year - 1
    academic_year_label = f"{start_year}/{start_year + 1}"

    sept_12 = datetime.date(start_year, 9, 12)
    while sept_12.weekday() != 5:
        sept_12 += datetime.timedelta(days=1)

    days_since_start = max(0, (today - sept_12).days)
    week_num = (days_since_start // 7) + 1
    study_day_index = days_since_start

    weekday_ar = ARABIC_WEEKDAYS[today.weekday()]
    date_ar = f"{to_ar_num(today.day)} {ARABIC_MONTHS[today.month]} {to_ar_num(today.year)}"
    is_thu_or_fri = today.weekday() in (3, 4)

    # النوافذ الفعلية لامتحانات الشهر لوزارة التربية والتعليم
    is_oct_exam = (today.month == 10 and 18 <= today.day <= 22)
    is_nov_exam = (today.month == 11 and 22 <= today.day <= 26)
    is_mar_exam = (today.month == 3 and 21 <= today.day <= 25)
    is_apr_exam = (today.month == 4 and 25 <= today.day <= 29)

    if today.month in (9, 10, 11, 12):
        term_label = "الفصل الدراسي الأول"
        term_progress_pct = min(96, max(12, int((week_num / 16.0) * 100)))
    elif today.month == 1:
        term_label = "مراجعات وامتحانات نصف العام"
        term_progress_pct = 100
    elif today.month in (2, 3, 4, 5):
        term_label = "الفصل الدراسي الثاني (ومعسكرات الحسم لثالثة ثانوي)"
        t2_week = max(1, week_num - 21)
        term_progress_pct = min(98, max(15, int((t2_week / 15.0) * 100)))
    else:
        term_label = "ليالي الامتحان وموسم الحسم والتأسيس"
        term_progress_pct = 100

    if today.month == 1:
        day_mode = "midyear_revision"
        mode_badge = "معسكر مراجعة ليلة امتحان نصف العام"
    elif today.month in (6, 7):
        day_mode = "final_marathon"
        mode_badge = "ماراثون ليالي الامتحان النهائية"
    elif is_oct_exam or is_nov_exam or is_mar_exam or is_apr_exam:
        day_mode = "monthly_exam"
        mode_badge = f"معسكر اختبار شهر {ARABIC_MONTHS[today.month]} الرسمي للوزارة"
    elif is_thu_or_fri:
        day_mode = "weekly_assessment"
        mode_badge = f"التقييم الأسبوعي رقم ({to_ar_num(week_num)}) لوزارة التربية والتعليم"
    else:
        day_mode = "regular_study"
        mode_badge = f"الأسبوع الدراسي ({to_ar_num(week_num)}) • خطة المنهج المعتمدة"

    return {
        "date_iso": today.isoformat(),
        "date_ar": date_ar,
        "weekday_ar": weekday_ar,
        "academic_year": academic_year_label,
        "week_num": week_num,
        "week_num_ar": to_ar_num(week_num),
        "study_day_index": study_day_index,
        "term_label": term_label,
        "term_progress_pct": term_progress_pct,
        "day_mode": day_mode,
        "mode_badge": mode_badge,
    }


def _pick_by_week(items: List[Any], week_num: int, offset: int = 0) -> Any:
    """
    اختيار الدرس المتزامن مع الأسبوع الدراسي الفعلي (بحيث يبدأ الأسبوع 7 مثلاً عند الدروس الفعلية لأواخر أكتوبر).
    """
    idx = (max(1, week_num - 1) + offset) % len(items)
    return items[idx]


