def get_academic_context(now_dt: datetime | None = None) -> dict:
    """
    يحسب تلقائياً لأي يوم في أي سنة دراسية (٢٠٢٦/٢٠٢٧ أو السنوات القادمة للأبد):
    - المرحلة الزمنية في التقويم المصري
    - رقم الأسبوع الدراسي ونسبة إنجاز الخطة
    - الدروس المحددة بدقة لليوم لكل صف (أولى، ثانية، ثالثة ثانوي — عام وبكالوريا)
    - هل اليوم معسكر تقييم أسبوعي للوزارة (الخميس/الجمعة) أم اختبار شهري أم يوم مذاكرة جديد
    """
    if now_dt is None:
        now_dt = datetime.now(CAIRO_TZ)
    today = now_dt.date()

    # تحديد بداية العام الدراسي تلقائياً لأي سنة (السبت منتصف سبتمبر)
    start_year = today.year if today.month >= 9 else today.year - 1
    term1_start = date(start_year, 9, 12)
    term1_end = date(start_year, 12, 26)
    midyear_exams_end = date(start_year + 1, 1, 24)
    term2_start = date(start_year + 1, 2, 7)
    term2_end = date(start_year + 1, 5, 8)
    finals_end = date(start_year + 1, 7, 15)

    weekday = today.weekday()  # Mon=0 .. Thu=3, Fri=4, Sat=5, Sun=6
    is_weekly_assessment = weekday in (3, 4)  # الخميس والجمعة = التقييم الأسبوعي للوزارة ولم المتراكم!
    is_monthly_exam_window = (today.month in (10, 11, 3, 4)) and (today.day >= 26)

    if today <= term1_end:
        days_elapsed = max(0, (today - term1_start).days)
        week_num = (days_elapsed // 7) + 1
        study_day_idx = (days_elapsed * 2) // 7  # يتدرج بهدوء وتوازن مع الأسابيع الفعلية
        g1 = GRADE_1_TERM_1[min(study_day_idx + (today.day % 2), len(GRADE_1_TERM_1) - 1)]
        g2 = GRADE_2_TERM_1[min(study_day_idx + (today.day % 2), len(GRADE_2_TERM_1) - 1)]
        g3_max = min(11 + (week_num // 2), len(GRADE_3_FULL_YEAR) - 1) if today.month <= 10 else min(20, len(GRADE_3_FULL_YEAR) - 1)
        if today.month <= 10:
            # في سبتمبر وأكتوبر: حصر صارم في الوحدة/الباب الأول أو بداية الثاني حسب الأسبوع الفعلي
            g3_idx = min(days_elapsed // 5, 10)
            g1 = GRADE_1_TERM_1[min(days_elapsed // 4, 14)]
            g2 = GRADE_2_TERM_1[min(days_elapsed // 4, 14)]
        else:
            g3_idx = min(days_elapsed // 4, g3_max)
        g3 = GRADE_3_FULL_YEAR[g3_idx]
        progress_pct = min(95, max(8, int((days_elapsed / 105) * 100)))
        term_label = f"الفصل الدراسي الأول {start_year}/{start_year + 1} • الأسبوع الدراسي {week_num}"
    elif today <= midyear_exams_end:
        week_num = 16
        idx = today.toordinal()
        g1 = GRADE_1_TERM_1[idx % len(GRADE_1_TERM_1)]
        g2 = GRADE_2_TERM_1[idx % len(GRADE_2_TERM_1)]
        g3 = GRADE_3_FULL_YEAR[min(18, idx % 19)]
        progress_pct = 100
        term_label = f"معسكر مراجعات امتحانات نصف العام {start_year}/{start_year + 1}"
    elif today < term2_start:
        week_num = 1
        idx = today.toordinal()
        g1 = GRADE_1_TERM_2[0]
        g2 = GRADE_2_TERM_2[0]
        g3 = GRADE_3_FULL_YEAR[18 + (idx % 4)]
        progress_pct = 50
        term_label = "معسكر إجازة نصف العام وتأسيس الترم الثاني"
    elif today <= term2_end:
        days_elapsed = max(0, (today - term2_start).days)
        week_num = (days_elapsed // 7) + 1
        g1 = GRADE_1_TERM_2[min(days_elapsed // 10, len(GRADE_1_TERM_2) - 1)]
        g2 = GRADE_2_TERM_2[min(days_elapsed // 11, len(GRADE_2_TERM_2) - 1)]
        g3 = GRADE_3_FULL_YEAR[min(18 + (days_elapsed // 8), len(GRADE_3_FULL_YEAR) - 1)]
        progress_pct = min(96, max(10, int((days_elapsed / 90) * 100)))
        term_label = f"الفصل الدراسي الثاني {start_year}/{start_year + 1} • الأسبوع الدراسي {week_num}"
    elif today <= finals_end:
        week_num = 30
        idx = today.toordinal()
        g1 = GRADE_1_TERM_2[idx % len(GRADE_1_TERM_2)]
        g2 = GRADE_2_TERM_2[idx % len(GRADE_2_TERM_2)]
        g3 = GRADE_3_FULL_YEAR[idx % len(GRADE_3_FULL_YEAR)]
        progress_pct = 100
        term_label = f"المعسكر النهائي وليالي امتحانات الثانوية العامة والبكالوريا {start_year + 1}"
    else:
        week_num = 1
        g1 = GRADE_1_TERM_1[0]
        g2 = GRADE_2_TERM_1[0]
        g3 = GRADE_3_FULL_YEAR[0]
        progress_pct = 10
        term_label = f"معسكر التأسيس المبكر للدفعة الجديدة {today.year}/{today.year + 1}"

    if is_monthly_exam_window:
        day_mode = "monthly_exam"
        mode_badge = f"معسكر التقييم الشهري لوزارة التربية والتعليم — شهر {today.strftime('%m')}"
    elif is_weekly_assessment:
        day_mode = "weekly_assessment"
        mode_badge = f"معسكر التقييم الأسبوعي رقم ({week_num}) لوزارة التربية والتعليم + لمّ المتراكم"
    else:
        day_mode = "regular_study"
        mode_badge = f"خطة التقفيل اليومية المنظمة • الأسبوع ({week_num})"

    # تناوب الصف الرئيسي في فيديو تحدي الـ 30 ثانية الليلي يومياً بين الصفوف الثلاثة
    spotlight_index = today.toordinal() % 3
    grades_bundle = [
        {"grade_code": "G1", "grade_title": "الصف الأول الثانوي (العام والبكالوريا المصرية)", **g1},
        {"grade_code": "G2", "grade_title": "الصف الثاني الثانوي (العام ومسارات البكالوريا)", **g2},
        {"grade_code": "G3", "grade_title": "الصف الثالث الثانوي (الثانوية العامة والبكالوريا)", **g3},
    ]

    return {
        "date_str": today.strftime("%Y-%m-%d"),
        "week_num": week_num,
        "term_label": term_label,
        "day_mode": day_mode,
        "mode_badge": mode_badge,
        "progress_pct": progress_pct,
        "grades": grades_bundle,
        "night_spotlight": grades_bundle[spotlight_index],
    }
